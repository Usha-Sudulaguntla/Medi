export function t(key, lang) {
  const entry = STRINGS[key];
  if (!entry) return key;
  return entry[lang] || entry.en;
}

// Bilingual line: returns "Native / English" (or just English if same).
export function bi(key, lang) {
  const entry = STRINGS[key];
  if (!entry) return key;
  const native = entry[lang] || entry.en;
  const en = entry.en;
  if (native === en) return en;
  return `${native} / ${en}`;
}

// BCP47 locale for a given language code (for SpeechSynthesis/Recognition).
export function bcp47For(lang) {
  const l = LANGUAGES.find((x) => x.code === lang);
  return l ? l.bcp47 : "en-IN";
}